const __getRandomCoord = (center: Coordinates, radiusKm: number): Coordinates => {
  const radiusDeg = radiusKm / 111;
  const angle = Math.random() * 2 * Math.PI;
  const r = Math.sqrt(Math.random()) * radiusDeg;
  return {
    lat: center.lat + r * Math.cos(angle),
    lng: center.lng + r * Math.sin(angle),
  };
};

const _generateRoadCoordinates = (center: Coordinates, lengthKm: number): Coordinates[] => {
  const points = 5 + Math.floor(Math.random() * 5);
  const coords: Coordinates[] = [];
  let current = { ...center };
  const angle = Math.random() * 2 * Math.PI;
  const stepDeg = (lengthKm / 111) / points;
  
  for (let i = 0; i < points; i++) {
    coords.push({ ...current });
    current = {
      lat: current.lat + stepDeg * Math.cos(angle) + (Math.random() - 0.5) * 0.001,
      lng: current.lng + stepDeg * Math.sin(angle) + (Math.random() - 0.5) * 0.001,
    };
  }
  return coords;
};

